# TWO RULES WHEN ADDING OR EDITING AN ENTRY, both learned the hard way:
#
# 1. The id's CASE MUST MATCH the manifest exactly. Installs run
#    `winget install --id <id> --exact`, and --exact is case-sensitive, so
#    "tailscale.tailscale" fails with "no package found" even though
#    "Tailscale.Tailscale" installs fine. Four entries were dead this way.
# 2. VERIFY the id before committing it, with `winget show --id <id> --exact`.
#    Judge it by winget printing "Found ... [id]", not by the exit code --
#    Microsoft Store entries exit non-zero even when they resolve. Packages do
#    get renamed (Zed.Zed -> ZedIndustries.Zed) and delisted.
