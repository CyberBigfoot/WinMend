"""WinMend reports: speedtest."""

from __future__ import annotations

import html


def render_speedtest_report_html(result, plan=None):
    """Standalone, self-contained HTML report of a run -- shareable proof for an
    ISP dispute, with plan comparison when the user has entered a plan."""
    esc = lambda x: html.escape(str(x))
    down = (result.get("download") or {}).get("mbps")
    up = (result.get("upload") or {}).get("mbps")
    idle = result.get("idle_latency") or {}
    server = result.get("server") or {}
    conn = result.get("connection") or {}
    rows = []

    def row(label, value):
        if value in (None, "", "None"):
            return
        rows.append(f"<tr><th>{esc(label)}</th><td>{esc(value)}</td></tr>")

    row("Download", f"{down:.1f} Mbps" if down is not None else None)
    row("Upload", f"{up:.1f} Mbps" if up is not None else None)
    row("Ping (idle)", f"{idle['min_ms']:.0f} ms" if idle.get("min_ms") is not None else None)
    row("Jitter", f"{idle['jitter_ms']:.1f} ms" if idle.get("jitter_ms") is not None else None)
    if plan and plan.get("down") and down is not None:
        row("Plan download", f"{plan['down']:.0f} Mbps  ·  getting {down / plan['down'] * 100:.0f}%")
    if plan and plan.get("up") and up is not None:
        row("Plan upload", f"{plan['up']:.0f} Mbps  ·  getting {up / plan['up'] * 100:.0f}%")
    for key, label in (("bufferbloat_download", "Bufferbloat (download)"),
                       ("bufferbloat_upload", "Bufferbloat (upload)")):
        grade = result.get(key)
        if grade and grade.get("grade") not in (None, "—"):
            row(label, f"grade {grade['grade']}  (+{grade.get('increase_ms', 0):.0f} ms)")
    dns = result.get("dns") or {}
    row("DNS lookup", f"{dns['avg_ms']:.0f} ms" if dns.get("avg_ms") is not None else None)
    if conn.get("type") == "wifi":
        detail = []
        if conn.get("link_mbps"):
            detail.append(f"{conn['link_mbps']:.0f} Mbps link")
        if conn.get("signal_pct") is not None:
            detail.append(f"{conn['signal_pct']}% signal")
        row("Connection", "Wi-Fi  ·  " + "  ·  ".join(detail) if detail else "Wi-Fi")
    elif conn.get("type") == "ethernet":
        row("Connection", "Ethernet" + (f"  ·  {conn['link_mbps']:.0f} Mbps link"
                                        if conn.get("link_mbps") else ""))
    row("Server", server.get("colo"))
    row("Your IP", server.get("ip"))
    row("Tested", result.get("started_at"))

    return (
        "<!doctype html><html><head><meta charset='utf-8'>"
        "<title>WinMend Speed Test Report</title><style>"
        "body{font-family:Segoe UI,Arial,sans-serif;background:#f3f3f3;color:#1a1a1a;"
        "margin:0;padding:32px;}h1{font-size:22px;margin:0 0 4px;}"
        ".sub{color:#707070;font-size:13px;margin-bottom:20px;}"
        "table{border-collapse:collapse;background:#fff;border:1px solid #e0e0e0;"
        "border-radius:8px;overflow:hidden;min-width:420px;}"
        "th,td{text-align:left;padding:10px 16px;border-bottom:1px solid #eee;font-size:14px;}"
        "th{color:#555;font-weight:600;width:200px;}td{font-weight:600;}"
        ".foot{color:#999;font-size:11px;margin-top:16px;}</style></head><body>"
        "<h1>WinMend — Internet Speed Test</h1>"
        f"<div class='sub'>Measured against Cloudflare's speed-test servers.</div>"
        f"<table>{''.join(rows)}</table>"
        "<div class='foot'>Generated by WinMend. Figures are real measurements at the "
        "time shown.</div></body></html>"
    )
